def record_snapshot(
    session_id: str,
    state: dict,
    source: str,
    activity: str | None = None,
    tenant_id: str | None = None,
) -> dict:
    """Persist a state projection and one authoritative memory record."""

    tenant = normalize_tenant_id(tenant_id or tenant_for_session(session_id))
    session = get_session(session_id, tenant_id=tenant) or {
        "session_id": session_id,
        "status": "unknown",
    }
    projection = _sqlite.build_projection(session, state, activity)
    now = _utc_now()

    with _connect() as connection:
        cursor = connection.execute(
            """
            INSERT INTO session_snapshots (
                session_id,
                tenant_id,
                captured_at,
                source,
                projection_json,
                state_json
            ) VALUES (%s, %s, %s, %s, %s, %s)
            RETURNING snapshot_id
            """,
            (
                session_id,
                tenant,
                now,
                source,
                _json(projection),
                _json(state or {}),
            ),
        )
        row = cursor.fetchone()
        snapshot_id = row["snapshot_id"] if row else 0

        _record_memory_record(
            connection,
            tenant_id=tenant,
            session_id=session_id,
            record_type="state_snapshot",
            source=source,
            captured_at=now,
            payload={
                "snapshot_id": snapshot_id,
                "activity": projection.get("session", {}).get("activity"),
                "state": state or {},
            },
        )

    return {
        "snapshot_id": snapshot_id,
        "session_id": session_id,
        "captured_at": now,
        "source": source,
    }


def get_latest_snapshot(
    session_id: str,
    tenant_id: str | None = None,
) -> dict | None:
    tenant = normalize_tenant_id(tenant_id or tenant_for_session(session_id))

    with _connect() as connection:
        row = connection.execute(
            """
            SELECT
                captured_at,
                source,
                projection_json,
                state_json
            FROM session_snapshots
            WHERE session_id = %s AND tenant_id = %s
            ORDER BY captured_at DESC, snapshot_id DESC
            LIMIT 1
            """,
            (session_id, tenant),
        ).fetchone()

    if row is None:
        return None

    projection = json.loads(row["projection_json"])
    state = json.loads(row["state_json"])

    session_view = projection.get("session") or {}
    derived_activity = _sqlite.derive_activity(session_view, state)
    if derived_activity in ("completed", "failed"):
        projection["session"] = {
            **session_view,
            "activity": derived_activity,
        }
    projection["snapshot"] = {
        "captured_at": row["captured_at"],
        "source": row["source"],
        "state": state,
    }

    return projection


