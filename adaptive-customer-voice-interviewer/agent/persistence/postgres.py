def fail_job(
    *,
    job_id: str,
    error: str,
    tenant_id: str | None = None,
    retry_delay_seconds: float = 0,
    fencing_token: str | None = None,
) -> dict | None:
    """Fail or requeue only a processing job held by the current owner."""

    tenant = normalize_tenant_id(tenant_id)
    now = _utc_now()

    with _connect() as connection:
        row = connection.execute(
            """
            SELECT attempts, max_attempts
            FROM background_jobs
            WHERE job_id = %s
              AND tenant_id = %s
              AND status = 'processing'
              AND fencing_token = %s
            FOR UPDATE
            """,
            (job_id, tenant, fencing_token),
        ).fetchone()

        if row is not None:
            can_retry = int(row["attempts"]) < int(row["max_attempts"])

            if can_retry:
                connection.execute(
                    """
                    UPDATE background_jobs
                    SET status = 'queued',
                        error = %s,
                        run_after = %s,
                        worker_id = NULL,
                        fencing_token = NULL,
                        heartbeat_at = NULL,
                        updated_at = %s
                    WHERE job_id = %s AND tenant_id = %s
                    """,
                    (
                        str(error),
                        _retry_after(retry_delay_seconds),
                        now,
                        job_id,
                        tenant,
                    ),
                )
            else:
                connection.execute(
                    """
                    UPDATE background_jobs
                    SET status = 'failed',
                        error = %s,
                        worker_id = NULL,
                        fencing_token = NULL,
                        heartbeat_at = NULL,
                        completed_at = %s,
                        updated_at = %s
                    WHERE job_id = %s AND tenant_id = %s
                    """,
                    (str(error), now, now, job_id, tenant),
                )

    return get_job(job_id=job_id, tenant_id=tenant)


