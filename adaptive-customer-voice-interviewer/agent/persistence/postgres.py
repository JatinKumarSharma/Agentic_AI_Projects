def _ensure_schema(connection: Any) -> None:
    for statement in _SCHEMA_STATEMENTS:
        connection.execute(statement)

    applied_at = _utc_now()
    for version in SCHEMA_VERSIONS:
        connection.execute(
            """
            INSERT INTO schema_migrations (version, applied_at, description)
            VALUES (%s, %s, %s)
            ON CONFLICT (version) DO NOTHING
            """,
            (
                version,
                applied_at,
                _SCHEMA_DESCRIPTIONS.get(version, version),
            ),
        )


def configure(database_url: Any = None, *, ensure_schema: bool = True) -> str:
    """Configure the PostgreSQL DSN and, by default, ensure the schema exists."""

    global _database_url

    resolved = str(
        database_url
        or os.getenv("CVI_DATABASE_URL")
        or os.getenv("DATABASE_URL")
        or ""
    ).strip()

    if not resolved:
        raise RuntimeError(
            "CVI_DATABASE_URL is required when "
            "CVI_PERSISTENCE_BACKEND=postgresql."
        )

    normalized_scheme = resolved.split("://", 1)[0].strip().lower()
    if normalized_scheme not in POSTGRES_SCHEMES:
        raise RuntimeError(
            "CVI_DATABASE_URL must be a PostgreSQL URL such as "
            "postgresql://user:password@host:5432/database."
        )

    _database_url = resolved

    if ensure_schema:
        with _connect() as connection:
            _ensure_schema(connection)

    return resolved


def database_path() -> str:
    """Return the configured DSN under the repository compatibility name."""

    if not _database_url:
        return configure()

    return _database_url


def apply_migrations(database_url: Any = None) -> list[str]:
    """Ensure schema exists and return the recorded schema versions."""

    if database_url is not None or _database_url is None:
        configure(database_url)

    with _connect() as connection:
        rows = connection.execute(
            "SELECT version FROM schema_migrations ORDER BY version"
        ).fetchall()

    return [row["version"] for row in rows]


def _pg_columns(connection: Any, table: str) -> list[str]:
    rows = connection.execute(
        """
        SELECT column_name
        FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = %s
        ORDER BY ordinal_position
        """,
        (table,),
    ).fetchall()
    return [row["column_name"] for row in rows]


def _pg_primary_key(connection: Any, table: str) -> list[str]:
    rows = connection.execute(
        """
        SELECT kcu.column_name AS column_name
        FROM information_schema.table_constraints tc
        JOIN information_schema.key_column_usage kcu
          ON tc.constraint_catalog = kcu.constraint_catalog
         AND tc.constraint_schema = kcu.constraint_schema
         AND tc.constraint_name = kcu.constraint_name
         AND tc.table_schema = kcu.table_schema
         AND tc.table_name = kcu.table_name
        WHERE tc.constraint_type = 'PRIMARY KEY'
          AND tc.table_schema = current_schema()
          AND tc.table_name = %s
        ORDER BY kcu.ordinal_position
        """,
        (table,),
    ).fetchall()
    return [row["column_name"] for row in rows]


def _pg_index(connection: Any, name: str, table: str) -> dict | None:
    row = connection.execute(
        """
        SELECT
            ix.indisunique AS is_unique,
            (ix.indpred IS NOT NULL) AS is_partial,
            COALESCE(
                array_agg(a.attname ORDER BY u.ordinality) FILTER (WHERE u.attnum > 0),
                ARRAY[]::text[]
            ) AS columns
        FROM pg_class i
        JOIN pg_index ix ON ix.indexrelid = i.oid
        JOIN pg_class t ON t.oid = ix.indrelid
        JOIN pg_namespace n ON n.oid = t.relnamespace
        CROSS JOIN LATERAL unnest(ix.indkey) WITH ORDINALITY AS u(attnum, ordinality)
        JOIN pg_attribute a
          ON a.attrelid = t.oid
         AND a.attnum = u.attnum
        WHERE n.nspname = current_schema()
          AND i.relname = %s
          AND t.relname = %s
        GROUP BY ix.indisunique, (ix.indpred IS NOT NULL)
        """,
        (name, table),
    ).fetchone()

    if row is None:
        return None

    return {
        "unique": bool(row["is_unique"]),
        "partial": bool(row["is_partial"]),
        "columns": list(row["columns"]),
    }


def verify_migration_invariants(database_url: Any = None) -> list[str]:
    """Return schema-integrity issues after migrations; empty means healthy.

    Verification never applies schema, so a missing constraint stays visible to
    the caller instead of being recreated by ``configure()``.
    """

    global _database_url

    if database_url is not None or not _database_url:
        resolved = str(
            database_url
            or os.getenv("CVI_DATABASE_URL")
            or os.getenv("DATABASE_URL")
            or ""
        ).strip()
        normalized_scheme = resolved.split("://", 1)[0].strip().lower()

        if not resolved or normalized_scheme not in POSTGRES_SCHEMES:
            raise RuntimeError(
                "CVI_DATABASE_URL is required to verify PostgreSQL migrations."
            )

        _database_url = resolved

    issues: list[str] = []

    with _connect() as connection:
        tables = {
            row["table_name"]
            for row in connection.execute(
                """
                SELECT table_name
                FROM information_schema.tables
                WHERE table_schema = current_schema()
                """
            ).fetchall()
        }

        for table in invariants.REQUIRED_TABLES:
            if table not in tables:
                issues.append(f"table {table} is missing")

        for table in invariants.TENANT_SCOPED_TABLES:
            if "tenant_id" not in _pg_columns(connection, table):
                issues.append(f"table {table} is missing tenant_id")

        for table, required in invariants.REQUIRED_COLUMNS.items():
            columns = _pg_columns(connection, table)
            for column in required:
                if column not in columns:
                    issues.append(f"table {table} is missing {column}")

        for table, expected in invariants.REQUIRED_PRIMARY_KEYS.items():
            actual = _pg_primary_key(connection, table)
            if actual != list(expected):
                issues.append(
                    f"table {table} primary key is {actual!r}, expected {list(expected)!r}"
                )

        for name, spec in invariants.REQUIRED_INDEXES.items():
            index = _pg_index(connection, name, spec["table"])
            if index is None:
                issues.append(f"index {name} is missing")
                continue

            if index["unique"] != spec["unique"]:
                issues.append(f"index {name} uniqueness changed")
            if spec["partial"] and not index["partial"]:
                issues.append(f"index {name} is no longer partial")

            if index["columns"] != list(spec["columns"]):
                issues.append(
                    f"index {name} columns are {index['columns']!r}, "
                    f"expected {list(spec['columns'])!r}"
                )

    return sorted(issues)


def health_check() -> tuple[str, str | None]:
    """Return repository readiness without exposing connection details."""

    try:
        with _connect() as connection:
            connection.execute("SELECT 1").fetchone()
        return "ok", None
    except Exception as exc:
        return "unavailable", str(exc)


