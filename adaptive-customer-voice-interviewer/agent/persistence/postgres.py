def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds")


def _json(value: Any) -> str:
    return json.dumps(value, default=str, ensure_ascii=False)


def _required_text(value: Any) -> str:
    text = str(value).strip() if value is not None else ""
    return text or "unspecified"


def _driver() -> tuple[Any, Any]:
    """Import the PostgreSQL driver only when a real connection is needed."""

    try:
        import psycopg
        from psycopg.rows import dict_row
    except ImportError as exc:
        raise RuntimeError(
            "PostgreSQL persistence requires psycopg. "
            "Install requirements.txt in the runtime image."
        ) from exc

    return psycopg, dict_row


def _driver_dsn() -> str:
    """Normalize alias schemes to a DSN psycopg accepts."""

    parsed = urlparse(_database_url or "")
    scheme = parsed.scheme.split("+", 1)[0]
    if scheme == "postgres":
        scheme = "postgresql"
    return urlunparse(parsed._replace(scheme=scheme))


@contextlib.contextmanager
def _connect() -> Iterator[Any]:
    """Yield a tenant-neutral PostgreSQL connection in one transaction."""

    if not _database_url:
        raise RuntimeError(
            "PostgreSQL repository is not configured. "
            "Set CVI_DATABASE_URL or call configure() first."
        )

    psycopg, dict_row = _driver()
    connection = psycopg.connect(_driver_dsn())
    connection.row_factory = dict_row

    try:
        with connection:
            yield connection
    finally:
        connection.close()


