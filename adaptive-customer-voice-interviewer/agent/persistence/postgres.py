def enqueue_job(
    *,
    job_id: str,
    job_type: str,
    session_id: str,
    payload: dict,
    tenant_id: str | None = None,
    max_attempts: int = 3,
    unique_active: bool = False,
    run_after: str | None = None,
) -> dict:
    """Append one durable background job in the queued state."""

    tenant = normalize_tenant_id(tenant_id)
    now = _utc_now()
    available_at = run_after or now

    with _connect() as connection:
        try:
            connection.execute(
                """
                INSERT INTO background_jobs (
                    job_id,
                    tenant_id,
                    session_id,
                    job_type,
                    dedupe_key,
                    status,
                    payload_json,
                    result_json,
                    error,
                    attempts,
                    max_attempts,
                    run_after,
                    worker_id,
                    created_at,
                    updated_at,
                    started_at,
                    completed_at
                ) VALUES (%s, %s, %s, %s, %s, 'queued', %s, NULL, NULL, 0, %s, %s, NULL, %s, %s, NULL, NULL)
                """,
                (
                    job_id,
                    tenant,
                    session_id,
                    job_type,
                    job_type if unique_active else None,
                    _json(
                        _sqlite.with_job_identity(
                            payload,
                            job_id=job_id,
                            job_type=job_type,
                            session_id=session_id,
                            tenant_id=tenant,
                        )
                    ),
                    int(max_attempts),
                    available_at,
                    now,
                    now,
                ),
            )
        except Exception as exc:
            if "idx_background_jobs_active_unique" in str(exc):
                raise DuplicateJobError(
                    f"Active {job_type} job already exists for {session_id}."
                ) from exc
            raise

        row = connection.execute(
            "SELECT * FROM background_jobs WHERE job_id = %s",
            (job_id,),
        ).fetchone()

    return _sqlite._job_from_row(row)


def claim_jobs(
    *,
    worker_id: str,
    job_types: list[str] | None = None,
    tenant_id: str | None = None,
    limit: int = 1,
    fencing_token: str | None = None,
) -> list[dict]:
    """Atomically claim due jobs for one worker."""

    if limit <= 0:
        return []

    clauses = ["status = 'queued'", "run_after <= %s"]
    params: list[Any] = [_utc_now()]

    if tenant_id is not None:
        clauses.append("tenant_id = %s")
        params.append(normalize_tenant_id(tenant_id))

    if job_types:
        clauses.append(f"job_type IN ({','.join('%s' for _ in job_types)})")
        params.extend(job_types)

    params.append(int(limit))
    now = _utc_now()

    with _connect() as connection:
        rows = connection.execute(
            f"""
            SELECT job_id
            FROM background_jobs
            WHERE {' AND '.join(clauses)}
            ORDER BY created_at, job_id
            LIMIT %s
            FOR UPDATE SKIP LOCKED
            """,
            params,
        ).fetchall()

        claimed = []
        for row in rows:
            job_id = row["job_id"]
            token = fencing_token or f"lease_{uuid4().hex}"
            connection.execute(
                """
                UPDATE background_jobs
                SET status = 'processing',
                    attempts = attempts + 1,
                    worker_id = %s,
                    fencing_token = %s,
                    heartbeat_at = %s,
                    started_at = %s,
                    updated_at = %s
                WHERE job_id = %s
                """,
                (worker_id, token, now, now, now, job_id),
            )
            updated = connection.execute(
                "SELECT * FROM background_jobs WHERE job_id = %s",
                (job_id,),
            ).fetchone()
            claimed.append(_sqlite._job_from_row(updated))

    return claimed


