def recover_stale_jobs(
    *,
    stale_before: str,
    tenant_id: str | None = None,
) -> int:
    tenant = normalize_tenant_id(tenant_id)
    now = _utc_now()
    clauses = [
        "status = 'processing'",
        "COALESCE(heartbeat_at, updated_at) < %s",
    ]
    params: list[Any] = [stale_before]

    if tenant_id is not None:
        clauses.append("tenant_id = %s")
        params.append(tenant)

    with _connect() as connection:
        rows = connection.execute(
            f"""
            SELECT job_id, attempts, max_attempts
            FROM background_jobs
            WHERE {' AND '.join(clauses)}
            FOR UPDATE SKIP LOCKED
            """,
            params,
        ).fetchall()

        for row in rows:
            if int(row["attempts"]) < int(row["max_attempts"]):
                connection.execute(
                    """
                    UPDATE background_jobs
                    SET status = 'queued',
                        run_after = %s,
                        worker_id = NULL,
                        fencing_token = NULL,
                        heartbeat_at = NULL,
                        error = 'worker_stale',
                        updated_at = %s
                    WHERE job_id = %s
                    """,
                    (now, now, row["job_id"]),
                )
            else:
                connection.execute(
                    """
                    UPDATE background_jobs
                    SET status = 'failed',
                        error = 'worker_stale',
                        worker_id = NULL,
                        fencing_token = NULL,
                        heartbeat_at = NULL,
                        completed_at = %s,
                        updated_at = %s
                    WHERE job_id = %s
                    """,
                    (now, now, row["job_id"]),
                )

    return len(rows)


